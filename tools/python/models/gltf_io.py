"""Minimal binary glTF 2.0 (.glb) writer/reader for the procedural model kit.

No external dependencies beyond numpy. Textures are NOT embedded: the game binds
texture sets by material name (``assets/textures/<id>_albedo.jpg`` ...).
"""
from __future__ import annotations

import json
import struct

import numpy as np

from meshlib import Node, Soup, merge

# Material id -> (baseColor linear RGBA, metallic, roughness, extra fields)
MATERIALS = {
    "stone_floor": ([0.26, 0.25, 0.23, 1.0], 0.0, 0.92, {}),
    "stone_wall": ([0.30, 0.285, 0.265, 1.0], 0.0, 0.90, {}),
    "stone_plate": ([0.36, 0.345, 0.32, 1.0], 0.0, 0.86, {}),
    "wood_dark": ([0.15, 0.095, 0.06, 1.0], 0.0, 0.74, {}),
    "bronze_aged": ([0.46, 0.34, 0.19, 1.0], 0.85, 0.45, {}),
    "iron_rusted": ([0.21, 0.165, 0.135, 1.0], 0.70, 0.70, {}),
    "cloth_wool": ([0.26, 0.055, 0.045, 1.0], 0.0, 0.95, {}),
    "parchment": ([0.70, 0.60, 0.43, 1.0], 0.0, 0.85, {}),
    "wax": ([0.86, 0.79, 0.63, 1.0], 0.0, 0.55, {}),
    "leather": ([0.24, 0.12, 0.065, 1.0], 0.0, 0.70, {}),
    "stained_glass": ([0.55, 0.35, 0.60, 0.65], 0.0, 0.25,
                      {"alphaMode": "BLEND", "doubleSided": True, "emissiveFactor": [0.10, 0.06, 0.12]}),
    "flame": ([1.0, 0.55, 0.18, 1.0], 0.0, 1.0, {"emissiveFactor": [1.0, 0.45, 0.12]}),
}
ALLOWED_MATERIALS = set(MATERIALS)
DOUBLE_SIDED = {"cloth_wool", "stained_glass"}

ARRAY_BUFFER, ELEMENT_ARRAY_BUFFER = 34962, 34963
FLOAT, USHORT, UINT, UBYTE = 5126, 5123, 5125, 5121


def weld(soup: Soup):
    """Soup -> (positions, normals, uvs, colors|None, indices)."""
    s = soup
    if s.normals is None:
        s = s.copy().shade()
    uv = s.uvs.copy()
    if np.isnan(uv).any():
        raise ValueError("unresolved UVs")
    p = s.tris.reshape(-1, 3)
    n = s.normals.reshape(-1, 3)
    t = uv.reshape(-1, 2)
    cols = None if s.colors is None else s.colors.reshape(-1, 4)
    feats = [np.round(p * 1e5), np.round(n * 1e3), np.round(t * 1e4)]
    if cols is not None:
        feats.append(np.round(cols * 255))
    key = np.concatenate(feats, 1).astype(np.int64)
    _, first, inv = np.unique(key, axis=0, return_index=True, return_inverse=True)
    inv = inv.reshape(-1)
    order = np.argsort(first)  # keep vertex order roughly stable
    remap = np.empty_like(order)
    remap[order] = np.arange(len(order))
    sel = first[order]
    idx = remap[inv].reshape(-1, 3)
    nn = n[sel]
    nn /= np.maximum(np.linalg.norm(nn, axis=1, keepdims=True), 1e-12)
    return (p[sel].astype(np.float32), nn.astype(np.float32), t[sel].astype(np.float32),
            None if cols is None else cols[sel].astype(np.float32), idx.astype(np.uint32))


class _Bin:
    def __init__(self):
        self.data = bytearray()
        self.views = []
        self.accessors = []

    def add(self, arr: np.ndarray, target, comp, typ, minmax=False, normalized=False):
        while len(self.data) % 4:
            self.data += b"\0"
        off = len(self.data)
        raw = arr.tobytes()
        self.data += raw
        view = {"buffer": 0, "byteOffset": off, "byteLength": len(raw)}
        if target:
            view["target"] = target
        self.views.append(view)
        count = arr.shape[0] if typ != "SCALAR" else arr.size
        acc = {"bufferView": len(self.views) - 1, "componentType": comp, "count": int(count), "type": typ}
        if normalized:
            acc["normalized"] = True
        if minmax:
            a2 = arr.reshape(count, -1)
            acc["min"] = [float(v) for v in a2.min(0)]
            acc["max"] = [float(v) for v in a2.max(0)]
        self.accessors.append(acc)
        return len(self.accessors) - 1


def write_glb(path, root: Node, asset_extras=None, default_uv_scale=None):
    """Write the node tree to ``path``. Returns stats dict."""
    default_uv_scale = default_uv_scale or {}
    gl = {"asset": {"version": "2.0", "generator": "mosteiro-procedural-models (python/numpy)",
                    "copyright": "Original procedural geometry generated by project code"},
          "scene": 0, "scenes": [{"name": root.name, "nodes": [0]}], "nodes": [], "meshes": [], "materials": []}
    if asset_extras:
        gl["asset"]["extras"] = asset_extras
    b = _Bin()
    mat_index = {}
    stats = {"triangles": 0, "vertices": 0, "materials": set()}

    def mat(name):
        if name not in mat_index:
            col, metal, rough, extra = MATERIALS[name]
            m = {"name": name, "pbrMetallicRoughness": {"baseColorFactor": col, "metallicFactor": metal,
                                                         "roughnessFactor": rough},
                 "extras": {"materialId": name}}
            m.update({k: v for k, v in extra.items()})
            if name in DOUBLE_SIDED:
                m["doubleSided"] = True
            mat_index[name] = len(gl["materials"])
            gl["materials"].append(m)
        return mat_index[name]

    def emit(node: Node):
        ni = len(gl["nodes"])
        nd = {"name": node.name}
        gl["nodes"].append(nd)
        if any(abs(v) > 1e-9 for v in node.translation):
            nd["translation"] = [float(v) for v in node.translation]
        if node.rotation is not None:
            nd["rotation"] = [float(v) for v in node.rotation]
        if node.extras:
            nd["extras"] = node.extras
        if node.parts:
            prims = []
            for mname in sorted(node.parts):
                soup = merge(*node.parts[mname])
                if len(soup) == 0:
                    continue
                if np.isnan(soup.uvs).any():
                    soup.box_uv(default_uv_scale.get(mname, 1.0), force=False)
                pos, nrm, uv, col, idx = weld(soup)
                if not np.isfinite(pos).all() or not np.isfinite(nrm).all():
                    raise ValueError(f"non-finite geometry in {node.name}/{mname}")
                attrs = {"POSITION": b.add(pos, ARRAY_BUFFER, FLOAT, "VEC3", minmax=True),
                         "NORMAL": b.add(nrm, ARRAY_BUFFER, FLOAT, "VEC3"),
                         "TEXCOORD_0": b.add(uv, ARRAY_BUFFER, FLOAT, "VEC2")}
                if col is not None:
                    attrs["COLOR_0"] = b.add(np.clip(col * 255 + 0.5, 0, 255).astype(np.uint8), ARRAY_BUFFER,
                                             UBYTE, "VEC4", normalized=True)
                if len(pos) < 65535:
                    ia = b.add(idx.astype(np.uint16).reshape(-1), ELEMENT_ARRAY_BUFFER, USHORT, "SCALAR")
                else:
                    ia = b.add(idx.reshape(-1), ELEMENT_ARRAY_BUFFER, UINT, "SCALAR")
                prims.append({"attributes": attrs, "indices": ia, "material": mat(mname), "mode": 4})
                stats["triangles"] += len(idx)
                stats["vertices"] += len(pos)
                stats["materials"].add(mname)
            if prims:
                nd["mesh"] = len(gl["meshes"])
                gl["meshes"].append({"name": node.name, "primitives": prims})
        kids = [emit(c) for c in node.children]
        if kids:
            nd["children"] = kids
        return ni

    emit(root)
    while len(b.data) % 4:
        b.data += b"\0"
    gl["buffers"] = [{"byteLength": len(b.data)}]
    gl["bufferViews"] = b.views
    gl["accessors"] = b.accessors
    js = json.dumps(gl, separators=(",", ":")).encode("utf-8")
    while len(js) % 4:
        js += b" "
    total = 12 + 8 + len(js) + 8 + len(b.data)
    with open(path, "wb") as f:
        f.write(struct.pack("<4sII", b"glTF", 2, total))
        f.write(struct.pack("<I4s", len(js), b"JSON"))
        f.write(js)
        f.write(struct.pack("<I4s", len(b.data), b"BIN\0"))
        f.write(bytes(b.data))
    stats["materials"] = sorted(stats["materials"])
    stats["bytes"] = total
    return stats


# --------------------------------------------------------------------------
# Reader (used by audit, tests and the preview renderer)
# --------------------------------------------------------------------------
_COMP = {5126: np.float32, 5123: np.uint16, 5125: np.uint32, 5121: np.uint8, 5120: np.int8, 5122: np.int16}
_NCOMP = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}


def read_glb(path):
    with open(path, "rb") as f:
        data = f.read()
    magic, version, length = struct.unpack_from("<4sII", data, 0)
    if magic != b"glTF" or version != 2 or length != len(data):
        raise ValueError(f"bad GLB header in {path}")
    jl, jt = struct.unpack_from("<I4s", data, 12)
    if jt != b"JSON":
        raise ValueError("first chunk must be JSON")
    js = json.loads(data[20:20 + jl].decode("utf-8"))
    off = 20 + jl
    binc = b""
    if off < len(data):
        bl, bt = struct.unpack_from("<I4s", data, off)
        if bt != b"BIN\0":
            raise ValueError("second chunk must be BIN")
        binc = data[off + 8: off + 8 + bl]
    return js, binc, {"json_len": jl, "bin_offset": off}


def accessor(js, binc, i):
    a = js["accessors"][i]
    v = js["bufferViews"][a["bufferView"]]
    dt = _COMP[a["componentType"]]
    nc = _NCOMP[a["type"]]
    start = v.get("byteOffset", 0) + a.get("byteOffset", 0)
    arr = np.frombuffer(binc, dtype=dt, count=a["count"] * nc, offset=start)
    return arr.reshape(a["count"], nc) if nc > 1 else arr


def _trs(nd):
    m = np.eye(4)
    if "matrix" in nd:
        return np.array(nd["matrix"]).reshape(4, 4).T
    t = nd.get("translation", [0, 0, 0])
    x, y, z, w = nd.get("rotation", [0, 0, 0, 1])
    s = nd.get("scale", [1, 1, 1])
    r = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                  [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                  [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
    m[:3, :3] = r * np.array(s)[None, :]
    m[:3, 3] = t
    return m


def world_primitives(js, binc):
    """Yield (node_name, material_name, world_positions(N,3), world_normals, indices(M,3), colors|None)."""
    out = []

    def walk(i, parent):
        nd = js["nodes"][i]
        m = parent @ _trs(nd)
        if "mesh" in nd:
            for pr in js["meshes"][nd["mesh"]]["primitives"]:
                pos = accessor(js, binc, pr["attributes"]["POSITION"]).astype(float)
                nrm = accessor(js, binc, pr["attributes"]["NORMAL"]).astype(float)
                idx = accessor(js, binc, pr["indices"]).astype(np.int64).reshape(-1, 3)
                col = None
                if "COLOR_0" in pr["attributes"]:
                    col = accessor(js, binc, pr["attributes"]["COLOR_0"]).astype(float) / 255.0
                wp = pos @ m[:3, :3].T + m[:3, 3]
                wn = nrm @ np.linalg.inv(m[:3, :3])
                mname = js["materials"][pr["material"]]["name"] if "material" in pr else "?"
                out.append((nd.get("name", ""), mname, wp, wn, idx, col))
        for c in nd.get("children", []):
            walk(c, m)

    for r in js["scenes"][js.get("scene", 0)]["nodes"]:
        walk(r, np.eye(4))
    return out


def node_world_positions(js):
    res = {}

    def walk(i, parent):
        nd = js["nodes"][i]
        m = parent @ _trs(nd)
        res[nd.get("name", str(i))] = m[:3, 3].copy()
        for c in nd.get("children", []):
            walk(c, m)

    for r in js["scenes"][js.get("scene", 0)]["nodes"]:
        walk(r, np.eye(4))
    return res
