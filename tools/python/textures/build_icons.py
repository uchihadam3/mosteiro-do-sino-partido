def note(cx, cy, s=1.0, flag=True):
    head = rot(E(cx, cy, 4.6 * s, 3.3 * s), -22, (cx, cy))
    stem = R(cx + 3.0 * s, cy - 22 * s, cx + 5.6 * s, cy)
    g = U(head, stem)
    if flag:
        g = U(g, P(("M", cx + 3.2 * s, cy - 22 * s), ("C", cx + 6 * s, cy - 16 * s, cx + 13 * s, cy - 15 * s, cx + 11 * s, cy - 7 * s),
                   ("C", cx + 10.5 * s, cy - 12 * s, cx + 7 * s, cy - 14.5 * s, cx + 3.2 * s, cy - 15 * s)))
    return g


def chevron(cx, cy, w=16, h=8, t=4.2, up=True):
    s = -1 if up else 1
    return Lw([(cx - w / 2, cy - s * h / 2), (cx, cy + s * h / 2), (cx + w / 2, cy - s * h / 2)], t, cap="flat", join="mitre")


def coin(cx, cy, r, emblem=True):
    g = cut(C(cx, cy, r), Ring(cx, cy, r - 3.2, 1.4))
    if emblem:
        b = scl(bell(24, 15, 31, hw=8.5), r / 18 * 0.62, r / 18 * 0.62, o=(24, 24))
        b = mv(b, cx - 24, cy - 24 + r * 0.02)
        g = cut(g, b.buffer(0.2))
    return g


def padlock(cx=24, cy=27):
    body = R(cx - 11, cy - 4, cx + 11, cy + 15, r=2.5)
    shackle = Arc(cx, cy - 6, 7.2, 180, 360, 3.6, cap="flat")
    legs = U(R(cx - 9, cy - 6.2, cx - 5.4, cy - 3), R(cx + 5.4, cy - 6.2, cx + 9, cy - 3))
    hole = U(C(cx, cy + 4, 2.6), Poly([(cx - 1.4, cy + 5), (cx + 1.4, cy + 5), (cx + 2, cy + 10.5), (cx - 2, cy + 10.5)]))
    return cut(U(body, shackle, legs), hole)


def keyhole(cx, cy, s=1.0):
    return U(C(cx, cy - 2 * s, 3.4 * s), Poly([(cx - 1.8 * s, cy), (cx + 1.8 * s, cy), (cx + 3 * s, cy + 8 * s), (cx - 3 * s, cy + 8 * s)]))


def pointed_arch(cx, base_y, hw, top_y, w=None):
    """Equilateral-ish pointed arch silhouette (filled), open at the bottom."""
    h = base_y - top_y
    spring = top_y + h * 0.42
    return P(("M", cx - hw, base_y), ("L", cx - hw, spring),
             ("C", cx - hw, spring - h * 0.25, cx - hw * 0.35, top_y + h * 0.06, cx, top_y),
             ("C", cx + hw * 0.35, top_y + h * 0.06, cx + hw, spring - h * 0.25, cx + hw, spring),
             ("L", cx + hw, base_y))


def helm(cx=24, cy=24):
    shell = P(("M", cx - 12, cy + 16), ("L", cx - 12, cy - 4), ("C", cx - 12, cy - 13, cx - 6, cy - 17, cx, cy - 17),
              ("C", cx + 6, cy - 17, cx + 12, cy - 13, cx + 12, cy - 4), ("L", cx + 12, cy + 16))
    slit = U(R(cx - 9, cy - 3.2, cx - 1.4, cy - 0.6), R(cx + 1.4, cy - 3.2, cx + 9, cy - 0.6))
    vents = U(*[C(cx + dx, cy + 6 + dy, 0.95) for dx in (-6, -3, 3, 6) for dy in (0, 3.2)])
    ridge = Lw([(cx, cy - 15), (cx, cy + 15)], 1.3, cap="flat")
    return cut(shell, slit, vents, ridge.difference(R(cx - 2, cy - 4, cx + 2, cy + 1)))


