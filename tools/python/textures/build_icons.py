def svg_doc(d):
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48" fill="currentColor">'
            f'<path fill="currentColor" fill-rule="evenodd" d="{d}"/></svg>\n')


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    symbols = []
    for iid, (fn, desc, cat) in ICONS.items():
        g = fn()
        d = to_path(g)
        if not d:
            raise RuntimeError(f"icon {iid} produced no geometry")
        (OUT / f"{iid}.svg").write_text(svg_doc(d))
        symbols.append(f'<symbol id="{iid}" viewBox="0 0 48 48"><path fill="currentColor" fill-rule="evenodd" d="{d}"/></symbol>')
        manifest[iid] = dict(file=f"{iid}.svg", category=cat, description=desc)
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n' + "\n".join(symbols) + "\n</svg>\n")
    (OUT / "icons.svg").write_text(sprite)
    man = dict(
        generator="tools/python/textures/build_icons.py",
        license="Original work generated procedurally by project code.",
        viewBox="0 0 48 48",
        color="currentColor (single path, fill-rule evenodd)",
        sprite="icons.svg",
        count=len(manifest),
        icons=manifest,
    )
    (OUT / "manifest.json").write_text(json.dumps(man, indent=2) + "\n")
    print(f"{len(manifest)} icons -> {OUT}")


def contact(path, ids=None, cols=12, big_px=64):
    import io

    import cairosvg
    from PIL import Image, ImageDraw

    ids = ids or list(ICONS)
    cell = max(120, big_px + 56)
    rows = math.ceil(len(ids) / cols)
    sheet = Image.new("RGB", (cols * cell, rows * cell), (26, 24, 22))
    d = ImageDraw.Draw(sheet)
    for i, iid in enumerate(ids):
        svg = (OUT / f"{iid}.svg").read_text().replace("currentColor", "#d8c7a3")
        big = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=big_px, output_height=big_px))).convert("RGBA")
        small = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.replace("#d8c7a3", "#b89a5a").encode(), output_width=20, output_height=20))).convert("RGBA")
        r, c = divmod(i, cols)
        x, y = c * cell, r * cell
        sheet.paste(big, (x + 8, y + 10), big)
        sheet.paste(small, (x + big_px + 20, y + 30), small)
        d.text((x + 4, y + big_px + 36), iid[:19], fill=(150, 140, 120))
    sheet.save(path)
    print("icon contact sheet ->", path)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--contact", help="also render a PNG contact sheet (requires cairosvg)")
    ap.add_argument("--only", nargs="*", help="limit contact sheet to these ids")
    ap.add_argument("--px", type=int, default=64, help="large preview size in the contact sheet")
    ap.add_argument("--cols", type=int, default=12)
    args = ap.parse_args(argv)
    build()
    if args.contact:
        contact(args.contact, args.only, cols=args.cols, big_px=args.px)


if __name__ == "__main__":
    main()
