"""Build the SVG icon set for Mosteiro do Sino Partido.

Run from the repository root:

    python3 tools/python/textures/build_icons.py
    python3 tools/python/textures/build_icons.py --contact /tmp/icons.png   # needs cairosvg

Every icon is composed from vector primitives with boolean geometry
(shapely) and written as ONE evenodd path on a 48x48 viewBox, filled with
``currentColor`` so CSS can tint it. Outputs:

    apps/web/public/assets/icons/<id>.svg
    apps/web/public/assets/icons/icons.svg       (sprite of <symbol id="<id>">)
    apps/web/public/assets/icons/manifest.json

All designs are original and generated by this file.
"""

