def wax_seal(cx=24, cy=24, r=18, seed=0):
    pts = []
    n = 72
    for i in range(n):
        a = 2 * math.pi * i / n
        rr = r + 1.6 * math.sin(a * 7 + seed) + 0.9 * math.sin(a * 13 + seed * 2.3)
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    blob = Poly(pts)
    return cut(blob, Ring(cx, cy, r - 5, 1.4))


