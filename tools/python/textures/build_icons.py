def rune_glyph(cx=24, cy=24, s=1.0, w=2.8):
    pts = [((0, -10), (0, 10)), ((0, -10), (6, -4)), ((0, -3), (-6, 3)), ((0, 2), (6, 8))]
    return U(*[Lw([(cx + a * s, cy + b * s), (cx + c * s, cy + d * s)], w) for (a, b), (c, d) in pts])


def footprint(cx, cy, s=1.0, ang=0, left=False):
    sole = U(E(cx, cy + 2 * s, 3.6 * s, 6.2 * s), E(cx, cy + 8.6 * s, 2.9 * s, 3.2 * s))
    sole = cut(sole, R(cx - 5 * s, cy + 5.6 * s, cx + 5 * s, cy + 6.6 * s))
    toes = U(*[C(cx + dx * s, cy + dy * s, r * s) for dx, dy, r in
               [(-2.6, -6.2, 1.5), (-0.4, -7.4, 1.4), (1.8, -7.0, 1.3), (3.6, -5.6, 1.15)]])
    g = U(sole, toes)
    if left:
        g = flipx(g, cx)
    return rot(g, ang, (cx, cy))


def hand_open(cx=24, cy=26):
    palm = R(cx - 8, cy - 4, cx + 7, cy + 10, r=4)
    fingers = [R(cx - 8 + i * 4, cy - 15 + (abs(i - 1.5) * 1.6), cx - 8 + i * 4 + 3.2, cy, r=1.6) for i in range(4)]
    thumb = rot(R(cx + 4, cy - 2, cx + 7.4, cy + 8, r=1.7), -38, (cx + 6, cy + 7))
    wrist = R(cx - 6, cy + 9, cx + 5, cy + 16, r=1)
    g = U(palm, *fingers, wrist)
    g = over(g, thumb, gap=1.2)
    for i in range(1, 4):
        g = cut(g, Lw([(cx - 8 + i * 4 - 0.4, cy - 10), (cx - 8 + i * 4 - 0.4, cy - 1)], 0.9, cap="flat"))
    return g


def rays(cx, cy, r0, r1, n, w=2.6, a0=-90):
    return U(*[Lw([(cx + r0 * math.cos(math.radians(a0 + 360 * i / n)), cy + r0 * math.sin(math.radians(a0 + 360 * i / n))),
                   (cx + r1 * math.cos(math.radians(a0 + 360 * i / n)), cy + r1 * math.sin(math.radians(a0 + 360 * i / n)))], w)
               for i in range(n)])


def wedge_rays(cx, cy, r0, r1, n, hw=2.2, a0=-90, alt=None):
    out = []
    for i in range(n):
        a = math.radians(a0 + 360 * i / n)
        rr1 = r1 if alt is None or i % 2 == 0 else alt
        ux, uy = math.cos(a), math.sin(a)
        tx, ty = -uy, ux
        out.append(Poly([(cx + ux * r0 + tx * hw, cy + uy * r0 + ty * hw), (cx + ux * rr1, cy + uy * rr1),
                         (cx + ux * r0 - tx * hw, cy + uy * r0 - ty * hw)]))
    return U(*out)


