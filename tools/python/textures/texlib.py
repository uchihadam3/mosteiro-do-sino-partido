class WrapCanvas:
    """Grayscale supersampled canvas whose primitives wrap at the borders."""

    def __init__(self, w, h=None, ss=1, mode="L", bg=0):
        self.w, self.h, self.ss = w, h or w, ss
        self.img = Image.new(mode, (self.w * ss, self.h * ss), bg)
        self.d = ImageDraw.Draw(self.img)

    def _offsets(self):
        for oy in (-self.h, 0, self.h):
            for ox in (-self.w, 0, self.w):
                yield ox, oy

    def line(self, pts, fill, width):
        s = self.ss
        for ox, oy in self._offsets():
            p = [((x + ox) * s, (y + oy) * s) for x, y in pts]
            self.d.line(p, fill=fill, width=max(1, int(round(width * s))), joint="curve")

    def ellipse(self, cx, cy, rx, ry, fill):
        s = self.ss
        for ox, oy in self._offsets():
            self.d.ellipse(
                [(cx - rx + ox) * s, (cy - ry + oy) * s, (cx + rx + ox) * s, (cy + ry + oy) * s],
                fill=fill,
            )

    def polygon(self, pts, fill):
        s = self.ss
        for ox, oy in self._offsets():
            self.d.polygon([((x + ox) * s, (y + oy) * s) for x, y in pts], fill=fill)

    def array(self):
        a = np.asarray(self.img, F32) / 255.0
        if self.ss > 1:  # box filter keeps the result exactly periodic
            s = self.ss
            a = a.reshape(self.h, s, self.w, s).mean(axis=(1, 3))
        return a


def to8(a):
    return np.clip(np.asarray(a) * 255.0 + 0.5, 0, 255).astype(np.uint8)


def circle_pts(cx, cy, r, n=64, a0=0.0, a1=2 * math.pi):
    return [(cx + r * math.cos(a0 + (a1 - a0) * i / (n - 1)), cy + r * math.sin(a0 + (a1 - a0) * i / (n - 1))) for i in range(n)]
