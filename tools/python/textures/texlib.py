class Perlin:
    """2D gradient noise, periodic with period 1 in (u, v)."""

    def __init__(self, period: int, seed: int):
        rng = np.random.default_rng(seed)
        a = rng.uniform(0, 2 * np.pi, (period, period))
        self.gx = np.cos(a).astype(F32)
        self.gy = np.sin(a).astype(F32)
        self.p = int(period)

    def __call__(self, u, v):
        p = self.p
        x = np.asarray(u, F32) * p
        y = np.asarray(v, F32) * p
        xi = np.floor(x)
        yi = np.floor(y)
        xf = x - xi
        yf = y - yi
        x0 = xi.astype(np.int64) % p
        y0 = yi.astype(np.int64) % p
        x1 = (x0 + 1) % p
        y1 = (y0 + 1) % p
        gx, gy = self.gx, self.gy

        def dot(ix, iy, dx, dy):
            return gx[iy, ix] * dx + gy[iy, ix] * dy

        n00 = dot(x0, y0, xf, yf)
        n10 = dot(x1, y0, xf - 1, yf)
        n01 = dot(x0, y1, xf, yf - 1)
        n11 = dot(x1, y1, xf - 1, yf - 1)
        fu = xf * xf * xf * (xf * (xf * 6 - 15) + 10)
        fv = yf * yf * yf * (yf * (yf * 6 - 15) + 10)
        a = n00 + (n10 - n00) * fu
        b = n01 + (n11 - n01) * fu
        return ((a + (b - a) * fv) * 1.4142).astype(F32)


def fbm(u, v, period, octaves, seed, gain=0.5, lac=2):
    total = np.zeros(np.shape(u), F32)
    amp, norm = 1.0, 0.0
    for o in range(octaves):
        total += amp * Perlin(int(period * lac**o), seed + 7919 * o)(u, v)
        norm += amp
        amp *= gain
    return total / norm


def ridged(u, v, period, octaves, seed, gain=0.5):
    total = np.zeros(np.shape(u), F32)
    amp, norm = 1.0, 0.0
    for o in range(octaves):
        n = 1.0 - np.abs(Perlin(int(period * 2**o), seed + 104729 * o)(u, v))
        total += amp * n * n
        norm += amp
        amp *= gain
    return total / norm


def spectral(n, seed, beta=2.0, ax=1.0, ay=1.0, fmin=0.0, fmax=None, m=None):
    """FFT-shaped noise (periodic). ``ax``/``ay`` > 1 compress features along
    that axis' frequency, i.e. ``ay=10`` gives streaks elongated along v."""
    m = m or n
    rng = np.random.default_rng(seed)
    f = np.fft.fft2(rng.standard_normal((m, n)))
    kx = np.fft.fftfreq(n) * n
    ky = np.fft.fftfreq(m) * m
    KX, KY = np.meshgrid(kx, ky)
    r = np.sqrt((KX * ax) ** 2 + (KY * ay) ** 2)
    r[0, 0] = 1.0
    amp = r ** (-beta / 2.0)
    amp[0, 0] = 0.0
    if fmin:
        amp *= 1.0 - np.exp(-((r / fmin) ** 2))
    if fmax:
        amp *= np.exp(-((r / fmax) ** 2))
    out = np.real(np.fft.ifft2(f * amp))
    return std(out)


def _q(u, v):
    q = np.stack([np.mod(np.ravel(u), 1.0), np.mod(np.ravel(v), 1.0)], -1)
    q[q >= 1.0] = 0.0
    return q


def worley(u, v, pts, k=2):
    tree = cKDTree(np.mod(pts, 1.0), boxsize=1.0)
    d, idx = tree.query(_q(u, v), k=k, workers=-1)
    shp = np.shape(u)
    if k == 1:
        return d.reshape(shp).astype(F32), idx.reshape(shp)
    return d.reshape(shp + (k,)).astype(F32), idx.reshape(shp + (k,))


def voronoi_edge(u, v, pts):
    """Returns (cell id, distance to nearest cell border, distance to site)
    in UV units, on the torus."""
    pts = np.mod(np.asarray(pts, np.float64), 1.0)
    tree = cKDTree(pts, boxsize=1.0)
    q = _q(u, v)
    d, idx = tree.query(q, k=3, workers=-1)
    d1 = wrapd(pts[idx[:, 0]] - q)
    best = np.full(len(q), np.inf)
    for j in (1, 2):
        dj = wrapd(pts[idx[:, j]] - q)
        num = (dj**2).sum(-1) - (d1**2).sum(-1)
        den = 2.0 * np.linalg.norm(dj - d1, axis=-1) + 1e-12
        best = np.minimum(best, num / den)
    shp = np.shape(u)
    return idx[:, 0].reshape(shp), best.reshape(shp).astype(F32), d[:, 0].reshape(shp).astype(F32)


def jitter_grid(gx, gy, jitter, rng):
    pts = []
    for j in range(gy):
        for i in range(gx):
            pts.append(
                ((i + 0.5 + rng.uniform(-jitter, jitter)) / gx,
                 (j + 0.5 + rng.uniform(-jitter, jitter)) / gy)
            )
    return np.mod(np.array(pts), 1.0)


def lloyd(pts, iters=2, res=256):
    u, v = grid(res)
    q = _q(u, v)
    for _ in range(iters):
        tree = cKDTree(np.mod(pts, 1.0), boxsize=1.0)
        _, idx = tree.query(q, k=1)
        off = wrapd(q - pts[idx])
        cnt = np.bincount(idx, minlength=len(pts)).astype(float) + 1e-9
        mx = np.bincount(idx, off[:, 0], minlength=len(pts)) / cnt
        my = np.bincount(idx, off[:, 1], minlength=len(pts)) / cnt
        pts = np.mod(pts + np.stack([mx, my], -1), 1.0)
    return pts


