def height_to_normal(h, strength):
    """Tangent-space normal, OpenGL convention (+X right, +Y up = toward the
    top of the image, +Z out). ``strength`` scales height units to pixels."""
    dx = ndimage.sobel(h, axis=1, mode="wrap") / 8.0
    dy = ndimage.sobel(h, axis=0, mode="wrap") / 8.0
    nx = -dx * strength
    ny = dy * strength  # image rows grow downward, so +Y up flips the sign
    nz = np.ones_like(h)
    n = np.stack([nx, ny, nz], -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return n.astype(F32)


def cavity(h, radii=(1.5, 4, 10, 24), weights=(1, 1, 0.8, 0.6)):
    c = np.zeros_like(h)
    for r, w in zip(radii, weights):
        c += w * np.clip(gblur(h, r) - h, 0, None)
    return c


def ao_from_height(h, k=6.0, radii=(1.5, 4, 10, 24), weights=(1, 1, 0.8, 0.6), floor=0.25):
    ao = 1.0 - np.clip(cavity(h, radii, weights) * k, 0, 1 - floor)
    return ao.astype(F32)


