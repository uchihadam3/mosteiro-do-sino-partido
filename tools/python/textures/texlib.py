"""Shared procedural-texture primitives for Mosteiro do Sino Partido.

Everything in here is periodic on the unit torus, so anything built from
these functions tiles seamlessly:

* ``Perlin``/``fbm``   - gradient noise whose lattice wraps (integer period).
* ``spectral``         - FFT-filtered white noise (periodic by construction),
                         optionally anisotropic for grain / streaks.
* ``worley``/``voronoi_edge`` - cellular noise evaluated with a periodic
                         KD-tree (``scipy.spatial.cKDTree(boxsize=1)``).
* ``gblur``            - gaussian blur with wrap-around borders.
* ``WrapCanvas``       - a Pillow canvas that draws every primitive 9 times
                         (offset by +-size) so strokes crossing the border
                         reappear on the opposite side.

All code and output is original and generated by this project.
"""

from __future__ import annotations

import math

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
from scipy.spatial import cKDTree

F32 = np.float32


# --------------------------------------------------------------------------
# basic math helpers
# --------------------------------------------------------------------------

def hexc(h: str) -> np.ndarray:
    h = h.lstrip("#")
    return np.array([int(h[i : i + 2], 16) for i in (0, 2, 4)], F32) / 255.0


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def lerp(a, b, t):
    """Linear blend; a scalar/2D weight broadcasts over colour channels."""
    t = np.asarray(t, F32)
    a = np.asarray(a, F32)
    b = np.asarray(b, F32)
    rgb = a.shape[-1:] == (3,) or b.shape[-1:] == (3,)
    if rgb and t.ndim == 2:
        t = t[..., None]
    return a + (b - a) * t


def ramp(colors, t):
    """Piecewise-linear colour ramp; ``colors`` are hex strings, t in [0,1]."""
    cs = np.stack([hexc(c) if isinstance(c, str) else c for c in colors])
    t = np.clip(np.asarray(t, F32), 0, 1) * (len(cs) - 1)
    i = np.clip(np.floor(t).astype(int), 0, len(cs) - 2)
    f = (t - i)[..., None]
    return cs[i] * (1 - f) + cs[i + 1] * f


def nrm(x):
    lo, hi = float(x.min()), float(x.max())
    return ((x - lo) / (hi - lo + 1e-9)).astype(F32)


def std(x):
    return ((x - x.mean()) / (x.std() + 1e-9)).astype(F32)


def grid(h: int, w: int | None = None):
    """Pixel-centre UV coordinates in [0,1): returns (u, v) with shape (h, w)."""
    w = w or h
    v, u = np.meshgrid(
        (np.arange(h, dtype=F32) + 0.5) / h,
        (np.arange(w, dtype=F32) + 0.5) / w,
        indexing="ij",
    )
    return u, v


def wrapd(d):
    """Shortest signed distance on the unit torus."""
    return d - np.round(d)


def gblur(x, s):
    if np.ndim(x) == 3:
        return ndimage.gaussian_filter(x, (s, s, 0), mode="wrap")
    return ndimage.gaussian_filter(x, s, mode="wrap")


