    if args.only and man_path.exists():
        old = {e["file"]: e for e in json.loads(man_path.read_text())["files"]}
    entries = []
    print("PBR sets:")
    for name in PBR_SETS:
        if args.only and name not in args.only:
            continue
        build_pbr(name, entries)
    print("Helper textures:")
    for name, (fn, purpose, tileable) in sprites.SPRITES.items():
        if args.only and name not in args.only:
            continue
        t0 = time.time()
        img = fn()
        fname = f"{name}.png"
        img.save(OUT / fname, optimize=True)
        entries.append(dict(
            file=fname, set=None, kind="sprite", width=img.width, height=img.height,
            bytes=(OUT / fname).stat().st_size, colorSpace="srgb", tileable=tileable,
            mode=img.mode, purpose=purpose,
        ))
        print(f"  {fname:24s} {img.width}x{img.height} {img.mode:4s} {time.time() - t0:5.1f}s")

    merged = dict(old)
    for e in entries:
        merged[e["file"]] = e
    files = sorted(merged.values(), key=lambda e: e["file"])
    total = sum(e["bytes"] for e in files)
    man = dict(
        generator="tools/python/textures/build_textures.py",
        license="Original work generated procedurally by project code; no third-party imagery.",
        normalConvention="OpenGL (+Y up), tangent space",
        totalBytes=total,
        files=files,
    )
    man_path.write_text(json.dumps(man, indent=2) + "\n")
    print(f"manifest: {len(files)} files, {total / 1e6:.2f} MB")


