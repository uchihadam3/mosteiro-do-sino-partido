def pct_step(x, lo, hi):
    """smoothstep between two percentiles of x (coverage control)."""
    a, b = np.percentile(x, [lo, hi])
    return smoothstep(a, b, x)


def stone_detail(u, v, n, seed):
    """Shared stone surface: mottling, mineral grains and faint veins."""
    mott = fbm(u, v, 6, 6, seed)
    grain = spectral(n, seed + 1, beta=0.4, fmin=90)
    g_light = smoothstep(1.5, 2.6, grain)
    g_dark = smoothstep(1.7, 2.8, -grain)
    vw = Perlin(3, seed + 2)(u + 0.06 * fbm(u, v, 8, 4, seed + 3), v + 0.06 * fbm(u, v, 8, 4, seed + 4))
    vein = (1 - smoothstep(0.0, 0.012, np.abs(vw))) * smoothstep(0.0, 0.25, fbm(u, v, 4, 2, seed + 5))
    fine = spectral(n, seed + 6, beta=1.1, fmin=40)
    return mott, g_light, g_dark, vein, fine


def angular_chips(u, v, n, ee, stone, seed, cells=60, p=0.4, depth=(3, 15)):
    """Chips with straight, faceted outlines: chips follow small Voronoi cells
    that touch the stone edge, so broken arrises look cut rather than eroded."""
    rng = np.random.default_rng(seed)
    pts = jitter_grid(cells, cells, 0.45, rng)
    cid, cedge, _ = voronoi_edge(u, v, pts)
    act = rng.random(len(pts)) < p
    dep = rng.uniform(*depth, len(pts)).astype(F32)
    tilt = rng.uniform(0.3, 1.0, len(pts)).astype(F32)
    chip = act[cid] & (ee < dep[cid]) & (stone > 0.5)
    chip = chip.astype(F32)
    # facet: depth proportional to closeness to the edge, plus a per-cell tilt
    facet = np.clip(1 - ee / dep[cid], 0, 1) * tilt[cid]
    return gblur(chip, 0.7), facet


def tex_stone_floor(n=1024, seed=101):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    wu = fbm(u, v, 4, 4, seed + 1) * 0.02
    wv = fbm(u, v, 4, 4, seed + 2) * 0.02
    pts = lloyd(jitter_grid(5, 5, 0.42, rng), iters=1)
    pts = np.concatenate([pts, rng.random((6, 2))])
    cid, edge, _ = voronoi_edge(u + wu, v + wv, pts)
    N = len(pts)
    e = edge * n
    grout_w = 2.6 + 1.6 * (fbm(u, v, 8, 2, seed + 4) + 0.5)
    ee = e - grout_w
    stone = smoothstep(-0.6, 0.9, ee)
    chip, facet = angular_chips(u, v, n, ee, stone, seed + 30, cells=64, p=0.35, depth=(3, 13))
    bevel = 1.0 - (1.0 - np.clip(ee / 7.0, 0, 1)) ** 2

    offs = rng.uniform(-0.035, 0.035, N).astype(F32)
    tone = rng.normal(0, 1, N).astype(F32)
    warm = (rng.uniform(0, 1, N) ** 2).astype(F32)
    tilt_a = rng.uniform(0, 2 * np.pi, N)
    tilt_m = rng.uniform(0, 0.04, N)
    du = wrapd(u - pts[cid, 0])
    dv = wrapd(v - pts[cid, 1])
    tilt = (np.cos(tilt_a)[cid] * du + np.sin(tilt_a)[cid] * dv) * tilt_m[cid] * 6

    mott, gl, gd, vein, fine = stone_detail(u, v, n, seed + 40)
    big = fbm(u, v, 2, 4, seed + 5)
    wear = fbm(u, v, 4, 4, seed + 8)

    pp = rng.random((1600, 2))
    pd, pi = worley(u, v, pp, k=1)
    prad = rng.uniform(0.7, 2.6, len(pp))[pi] / n
    pits = np.clip(1 - pd / prad, 0, 1) ** 1.3 * (rng.random(len(pp)) < 0.5)[pi]

    cw = Perlin(5, seed + 9)(u + 0.025 * fbm(u, v, 24, 3, seed + 10), v + 0.025 * fbm(u, v, 24, 3, seed + 11))
    crack_line = 1.0 - smoothstep(0.003, 0.012, np.abs(cw))
    crack_mask = smoothstep(0.05, 0.2, fbm(u, v, 3, 2, seed + 12)) * (rng.random(N) < 0.45)[cid]
    crack = crack_line * crack_mask * stone * (1 - chip)

    bump = spectral(n, seed + 50, beta=2.4, fmin=5)
    h_stone = 0.62 + 0.16 * bevel + offs[cid] + tilt + 0.035 * mott + 0.006 * fine + 0.018 * bump
    h_stone -= 0.035 * smoothstep(0.0, 0.4, wear)
    h_stone -= chip * (0.05 + 0.08 * facet)
    h_stone -= pits * 0.08 + crack * 0.14
    h_grout = 0.2 + 0.03 * mott + 0.015 * fine
    h = lerp(h_grout, h_stone, stone).astype(F32)

    t = 0.5 + 0.075 * tone[cid] + 0.6 * mott + 0.04 * fine + 0.05 * bump
    col = ramp(["#3c3a37", "#52504c", "#66645f", "#7a7770"], t)
    col = lerp(col, hexc("#6a6254"), warm[cid] * 0.5)
    col = lerp(col, hexc("#8a877f"), gl * 0.35)
    col = lerp(col, hexc("#2c2a28"), gd * 0.4)
    col = lerp(col, hexc("#878279"), vein * 0.22)
    col *= (1.0 + 0.07 * smoothstep(0.05, 0.45, wear))[..., None]
    col = lerp(col, col * 1.06 + 0.01, chip * 0.5)
    col *= (1.0 - 0.18 * (1 - bevel))[..., None]

    damp = smoothstep(0.0, 0.3, big + 0.2 * mott)
    col = col * (1.0 - 0.26 * damp)[..., None] + hexc("#1d2321") * (0.04 * damp)[..., None]

    grout_col = ramp(["#1c1a18", "#2a2724", "#36322d"], 0.5 + mott)
    col = lerp(grout_col, col, stone)
    col *= (1.0 - 0.4 * pits)[..., None]
    col = lerp(col, hexc("#161412"), crack * 0.75)

    cav = cavity(h, radii=(1.5, 4, 10), weights=(1, 1, 0.7))
    ash = np.clip(cav * 14, 0, 1) * smoothstep(-0.3, 0.3, fbm(u, v, 14, 3, seed + 13)) * (1 - 0.8 * damp)
    ash = np.maximum(ash, (1 - stone) * 0.5 * smoothstep(-0.15, 0.35, fbm(u, v, 9, 3, seed + 14)))
    col = lerp(col, hexc("#88837a"), np.clip(ash, 0, 1) * 0.6)

    rough = 0.84 + 0.05 * mott - 0.1 * smoothstep(0.05, 0.45, wear) + 0.05 * chip
    rough = lerp(rough, 0.48, damp * 0.85)
    rough = lerp(rough, 0.96, np.maximum(1 - stone, ash))
    ao = ao_from_height(h, k=7.0)
    return dict(albedo=col, height=h, rough=rough, ao=ao, strength=12.0)


def tex_stone_wall(n=1024, seed=202):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    x = u * n
    y = v * n
    X = np.mod(x + fbm(u, v, 6, 3, seed + 1) * 3, n)
    Y = np.mod(y + fbm(u, v, 6, 3, seed + 2) * 2.5, n)
    rows = [176, 160, 176, 160, 176, 176]
    starts = np.concatenate([[0], np.cumsum(rows)[:-1]]).astype(F32)
    ridx = np.clip(np.searchsorted(starts, Y, side="right") - 1, 0, len(rows) - 1)
    y0 = starts[ridx]
    y1 = y0 + np.array(rows, F32)[ridx]
    ex = np.zeros_like(X)
    bid = np.zeros(X.shape, np.int64)
    nb = 0
    prev_cuts = np.array([])
    for r in range(len(rows)):
        for _try in range(200):  # stagger joints against the previous course
            off = rng.uniform(0, n)
            widths = []
            while sum(widths) < n:
                widths.append(rng.uniform(260, 460))
            widths = np.array(widths) * (n / sum(widths))
            cum = np.cumsum(widths)
            cuts = np.mod(off + np.concatenate([[0], cum[:-1]]), n)
            if len(prev_cuts) == 0:
                break
            dmin = np.min(np.abs(wrapd((cuts[:, None] - prev_cuts[None, :]) / n))) * n
            if dmin > 80:
                break
        prev_cuts = cuts
        m = ridx == r
        dx = np.mod(X[m] - off, n)
        b = np.clip(np.searchsorted(cum, dx, side="right"), 0, len(cum) - 1)
        x0 = np.where(b > 0, cum[np.maximum(b - 1, 0)], 0.0)
        x1 = cum[b]
        ex[m] = np.minimum(dx - x0, x1 - dx)
        bid[m] = nb + b
        nb += len(cum)
    ey = np.minimum(Y - y0, y1 - Y)
    e = np.minimum(ex, ey)
    mortar = 2.6 + 1.4 * (fbm(u, v, 10, 2, seed + 5) + 0.5)
    ee = e - mortar
    stone = smoothstep(-0.6, 0.9, ee)
    chip, facet = angular_chips(u, v, n, ee, stone, seed + 30, cells=70, p=0.45, depth=(3, 16))
    corner = np.clip(1 - np.hypot(ex, ey) / 26, 0, 1)
    chip2, facet2 = angular_chips(u, v, n, ee, stone, seed + 31, cells=40, p=0.9, depth=(6, 22))
    chip = np.maximum(chip, chip2 * (corner > 0.1))
    facet = np.maximum(facet, facet2 * (corner > 0.1))
    bevel = 1.0 - (1.0 - np.clip(ee / 6.0, 0, 1)) ** 2

    NB = nb
    tone = rng.normal(0, 1, NB).astype(F32)
    warm = (rng.random(NB) ** 2.5).astype(F32)
    face = rng.uniform(-0.03, 0.03, NB).astype(F32)
    ang = rng.uniform(0.6, 1.0, NB) * rng.choice([-1, 1], NB)
    sootb = (rng.random(NB) ** 1.5).astype(F32)
    # each block gets its own offset into the shared detail fields
    mott, gl, gd, vein, fine = stone_detail(u, v, n, seed + 40)
    ox = rng.integers(0, n, NB)
    oy = rng.integers(0, n, NB)
    yi = (y.astype(np.int64) + oy[bid]) % n
    xi = (x.astype(np.int64) + ox[bid]) % n
    stone_m = stone > 0.01
    for arr in (mott, gl, gd, vein, fine):
        arr[stone_m] = arr[yi[stone_m], xi[stone_m]]

    pillow = np.sqrt(np.clip(np.minimum(ex, ey) / 40.0, 0, 1))
    tool = np.sin((X * np.cos(ang[bid]) + Y * np.sin(ang[bid])) * (2 * np.pi / 6.0) + 2.0 * fbm(u, v, 30, 2, seed + 8))
    tool_mask = smoothstep(-0.1, 0.4, fbm(u, v, 6, 3, seed + 9))
    bump = spectral(n, seed + 50, beta=2.4, fmin=5)
    h_stone = 0.62 + 0.14 * bevel + 0.04 * pillow + 0.018 * bump + face[bid] + 0.03 * mott + 0.006 * fine + 0.006 * tool * tool_mask
    pp = rng.random((1000, 2))
    pd, pi = worley(u, v, pp, k=1)
    pits = np.clip(1 - pd / (rng.uniform(0.8, 2.6, len(pp))[pi] / n), 0, 1) ** 1.3 * (rng.random(len(pp)) < 0.45)[pi]
    h_stone -= pits * 0.08 + chip * (0.05 + 0.08 * facet)
    h_mortar = 0.22 + 0.04 * fbm(u, v, 16, 4, seed + 15) + 0.02 * fine
    h = lerp(h_mortar, h_stone, stone).astype(F32)

    t = 0.5 + 0.11 * tone[bid] + 0.6 * mott + 0.04 * fine + 0.05 * bump
    col = ramp(["#42403c", "#57554f", "#696762", "#7c7972"], t)
    col = lerp(col, hexc("#76695a"), warm[bid] * 0.65)
    cool = (rng.random(NB) < 0.25).astype(F32)
    col = lerp(col, hexc("#55595a"), cool[bid] * 0.35)
    col = lerp(col, hexc("#8a867d"), gl * 0.3)
    col = lerp(col, hexc("#2b2927"), gd * 0.35)
    col = lerp(col, hexc("#86817a"), vein * 0.18)
    col = lerp(col, col * 1.06 + 0.01, chip * 0.5)
    col *= (1.0 - 0.16 * (1 - bevel))[..., None]

    ty = np.clip((Y - y0) / (y1 - y0), 0, 1)
    streak = smoothstep(0.3, 1.9, spectral(n, seed + 10, beta=1.2, ax=1, ay=9, fmin=2))
    broad = smoothstep(-0.15, 0.4, fbm(u, v, 2, 4, seed + 11))
    soot = sootb[bid] * (1 - ty) ** 1.8 * 0.45 + 0.45 * streak * broad + 0.3 * broad
    soot = np.clip(soot, 0, 1)
    col = lerp(col, hexc("#1c1a18"), soot * 0.68)

    mortar_col = ramp(["#2a2724", "#3a3631", "#47423b"], 0.5 + mott)
    col = lerp(mortar_col, col, stone)
    col *= (1.0 - 0.4 * pits)[..., None]
    cav = cavity(h, radii=(1.5, 4, 10), weights=(1, 1, 0.7))
    ash = np.clip(cav * 12, 0, 1) * smoothstep(-0.3, 0.3, fbm(u, v, 12, 3, seed + 12)) * (1 - soot)
    col = lerp(col, hexc("#7f7a72"), ash * 0.5)

    rough = 0.86 + 0.05 * mott + 0.05 * soot
    rough = lerp(rough, 0.95, 1 - stone)
    ao = ao_from_height(h, k=7.0)
    return dict(albedo=col, height=h, rough=np.clip(rough, 0, 1), ao=ao, strength=12.0)


def tex_stone_plate(n=1024, seed=303):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    x, y = u * n, v * n
    ex = np.minimum(x, n - x)
    ey = np.minimum(y, n - y)
    e = np.minimum(ex, ey)
    edge = smoothstep(1.0, 12.0, e)
    edge = 1 - (1 - edge) ** 2
    chip, facet = angular_chips(u, v, n, e - 1.0, np.ones_like(e), seed + 30, cells=80, p=0.25, depth=(4, 12))

    def rect_line(d, w):
        sd = np.maximum(d - ex, d - ey)
        return 1 - smoothstep(w * 0.5, w * 0.5 + 1.4, np.abs(sd))

    g1 = rect_line(60, 5.0)
    g2 = rect_line(78, 2.2)
    dd = np.abs(ex - 69) + np.abs(ey - 69)
    loz = 1 - smoothstep(1.4, 2.8, np.abs(dd - 15))
    loz_fill = 1 - smoothstep(5.0, 6.4, dd)
    mid_d = np.minimum(np.abs(x - n / 2), np.abs(y - n / 2))
    tick = (1 - smoothstep(1.0, 2.4, mid_d)) * ((e > 60) & (e < 78)).astype(F32)
    groove = np.clip(np.maximum.reduce([g1, g2 * 0.85, loz, tick * 0.85]), 0, 1)

    mott, gl, gd, vein, fine = stone_detail(u, v, n, seed + 40)
    wear = fbm(u, v, 3, 3, seed + 4)
    sp = rng.random((500, 2))
    sd_, si = worley(u, v, sp, k=1)
    speck = np.clip(1 - sd_ / (rng.uniform(0.6, 1.8, len(sp))[si] / n), 0, 1) * (rng.random(len(sp)) < 0.5)[si]

    h = 0.3 + 0.45 * edge + 0.01 * mott + 0.003 * fine
    h -= groove * 0.06 * edge + loz_fill * 0.02 + speck * 0.03 + chip * (0.04 + 0.06 * facet)
    h = h.astype(F32)

    col = ramp(["#5a5853", "#65635d", "#706d66"], 0.5 + 0.5 * mott + 0.04 * fine)
    col = lerp(col, hexc("#6d665b"), smoothstep(-0.1, 0.4, fbm(u, v, 2, 3, seed + 5)) * 0.3)
    col = lerp(col, hexc("#7c7871"), gl * 0.18)
    col = lerp(col, hexc("#45423e"), gd * 0.18)
    col = lerp(col, hexc("#7e7a73"), vein * 0.12)
    col *= (1.0 + 0.05 * smoothstep(0.0, 0.5, wear))[..., None]
    dust = groove * edge * (0.75 + 0.25 * smoothstep(-0.3, 0.3, fbm(u, v, 20, 2, seed + 6)))
    col = lerp(col, hexc("#8b867d"), dust * 0.5)
    col = lerp(col, col * 1.08, chip * 0.7)
    col = lerp(col, hexc("#33302c"), (1 - edge) * 0.7)
    col *= (1.0 - 0.25 * speck)[..., None]

    rough = 0.64 + 0.05 * mott - 0.08 * smoothstep(0.0, 0.5, wear)
    rough = lerp(rough, 0.9, np.maximum(dust, 1 - edge))
    ao = ao_from_height(h, k=8.0, radii=(1.5, 4, 10), weights=(1, 1, 0.5))
    return dict(albedo=col, height=h, rough=rough, ao=ao, strength=9.0)


def tex_wood_dark(n=1024, seed=404):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    x = u * n
    y = v * n
    widths = np.array([196, 212, 204, 220, 192], F32)
    cum = np.cumsum(widths)
    pidx = np.clip(np.searchsorted(cum, x, side="right"), 0, len(widths) - 1)
    px0 = np.where(pidx > 0, cum[np.maximum(pidx - 1, 0)], 0.0)
    pw = widths[pidx]
    ux = x - px0

    joints = []
    for p in range(len(widths)):
        k = rng.integers(1, 3)
        j = np.sort(rng.uniform(0, n, k))
        if k == 2 and (j[1] - j[0] < 300 or n - (j[1] - j[0]) < 300):
            j = j[:1]
        joints.append(j)
    seg = np.zeros(x.shape, np.int64)
    jd = np.full(x.shape, 1e9, F32)
    for p in range(len(widths)):
        m = pidx == p
        jj = joints[p]
        yy = y[m]
        s = np.searchsorted(jj, yy, side="right") % len(jj)
        seg[m] = p * 4 + s
        dmin = np.full(yy.shape, 1e9, F32)
        for jv in jj:
            dmin = np.minimum(dmin, np.abs(wrapd((yy - jv) / n)) * n)
        jd[m] = dmin
    S = len(widths) * 4
    sx = rng.integers(0, n, S)
    sy = rng.integers(0, n, S)
    rings = rng.uniform(7.0, 12.0, S).astype(F32)
    phase = rng.uniform(0, 1, S).astype(F32)
    tone = rng.normal(0, 1, S).astype(F32)
    cathedral = rng.uniform(0.0, 1.0, S).astype(F32)

    A = spectral(n, seed + 1, beta=4.0, ax=2.0, ay=6, fmin=0.5)  # slow sway of the growth rings
    Bf = spectral(n, seed + 2, beta=0.3, ax=0.25, ay=12, fmax=600)  # fibres / pores
    C = spectral(n, seed + 3, beta=1.0, ax=6, ay=1, fmin=25)  # medullary flecks
    D = spectral(n, seed + 4, beta=2.0, ax=1, ay=3)
    ys = (y.astype(np.int64) + sy[seg]) % n
    xs = (x.astype(np.int64) + sx[seg]) % n
    a, bf, c, d = A[ys, xs], Bf[ys, xs], C[ys, xs], D[ys, xs]
    yl = ys.astype(F32) / n

    # cathedral arches: rings bend as a slow function of v
    arch = cathedral[seg] * 0.8 * np.sin(yl * 2 * np.pi * 2 + phase[seg] * 6) * (ux / pw - 0.5) ** 2 * 6
    tg = ux / pw * rings[seg] + 0.55 * a + 0.06 * d + arch + phase[seg] * 3
    ring = tg - np.floor(tg)
    late = smoothstep(0.62, 0.86, ring) * (1 - smoothstep(0.9, 0.99, ring))
    line = np.exp(-(((ring - 0.9) / 0.03) ** 2))
    fib = np.clip(bf, -3, 3)
    pores = smoothstep(1.4, 2.8, -bf) * (0.4 + 0.6 * late)
    flecks = smoothstep(2.1, 3.0, c)

    gap_x = np.minimum(ux, pw - ux)
    ge = np.minimum(gap_x, jd)
    gap = smoothstep(1.2, 3.0, ge)
    bevel = 1 - (1 - np.clip((ge - 1.2) / 7.0, 0, 1)) ** 2

    nail = np.zeros_like(x)
    for p in range(len(widths)):
        for jv in joints[p]:
            for fx in (0.24, 0.76):
                for side in (-1, 1):
                    cx = cum[p] - widths[p] + widths[p] * fx
                    cy = (jv + side * 16) % n
                    dd = np.hypot(np.abs(wrapd((x - cx) / n)) * n, np.abs(wrapd((y - cy) / n)) * n)
                    nail = np.maximum(nail, np.clip(1 - dd / 6.5, 0, 1))
    nail_mask = smoothstep(0.0, 0.15, nail)
    nail_dome = np.sqrt(np.clip(nail, 0, 1))

    pp = rng.random((260, 2))
    pd, pi = worley(u, v, pp, k=1)
    dents = np.clip(1 - pd / (rng.uniform(2.0, 7.0, len(pp))[pi] / n), 0, 1) ** 2 * (rng.random(len(pp)) < 0.5)[pi]
    cw = WrapCanvas(n, ss=2)
    for _ in range(90):
        x0, y0 = rng.uniform(0, n, 2)
        ang = np.pi / 2 + rng.normal(0, 0.5)
        L = rng.uniform(20, 120)
        cw.line([(x0, y0), (x0 + L * math.cos(ang), y0 + L * math.sin(ang))], fill=int(rng.uniform(60, 200)), width=rng.uniform(0.6, 1.3))
    scratch = cw.array() * gap

    cup = 1 - (2 * ux / pw - 1) ** 2
    h = 0.55 + 0.03 * cup + 0.025 * late + 0.006 * fib - 0.02 * pores + 0.12 * bevel
    h -= 0.03 * dents + 0.012 * scratch
    h = lerp(0.05, h, gap)
    h = lerp(h, h + 0.02 + 0.03 * nail_dome, nail_mask).astype(F32)

    t = 0.62 + 0.08 * tone[seg] + 0.05 * a - 0.3 * late - 0.14 * line + 0.07 * fib
    col = ramp(["#120b07", "#1f140d", "#2f2016", "#423021", "#58412c", "#6a4f36"], t)
    col *= (1.0 - 0.3 * pores)[..., None]
    col = lerp(col, hexc("#6b5239"), flecks * 0.35)
    col = lerp(col, col * 1.2, (1 - bevel) * gap * 0.6)
    col = lerp(col, hexc("#6a5440"), scratch * 0.35)
    col = lerp(hexc("#070504"), col, gap)
    col = lerp(col, hexc("#1a1715"), nail_mask)
    col = lerp(col, hexc("#3d2a1c"), nail_mask * smoothstep(0.75, 0.2, nail) * 0.6)
    col *= (1.0 - 0.15 * dents)[..., None]
    grime = np.clip(cavity(h, radii=(2, 6), weights=(1, 1)) * 10, 0, 1)
