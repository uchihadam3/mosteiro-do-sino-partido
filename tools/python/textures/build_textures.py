def save_jpg(path, arr, q=JPEG_Q, gray=False, sub=2):
    img = Image.fromarray(to8(arr), "L" if gray else "RGB")
    if gray:
        img.save(path, quality=q, optimize=True)
    else:
        img.save(path, quality=q, optimize=True, subsampling=sub)


def build_pbr(name, manifest):
    fn, size, purpose = PBR_SETS[name]
    t0 = time.time()
    m = fn(size)
    albedo = np.clip(m["albedo"], 0, 1)
    nmap = height_to_normal(m["height"], m["strength"] * size / 1024 * 1.0)
    files = {
        "albedo": (albedo, False, "srgb"),
        "normal": (nmap * 0.5 + 0.5, False, "linear"),
        "rough": (np.clip(m["rough"], 0, 1), True, "linear"),
        "ao": (np.clip(m["ao"], 0, 1), True, "linear"),
    }
    if "metal" in m:
        files["metal"] = (np.clip(m["metal"], 0, 1), True, "linear")
    for kind, (arr, gray, cs) in files.items():
        fname = f"{name}_{kind}.jpg"
        q = NORMAL_Q if kind == "normal" else JPEG_Q
        save_jpg(OUT / fname, arr, q=q, gray=gray, sub=0 if kind == "normal" else 2)
        manifest.append(dict(
            file=fname, set=name, kind=kind, width=size, height=size,
            bytes=(OUT / fname).stat().st_size, colorSpace=cs, tileable=True,
            purpose=f"{purpose} [{kind}{', OpenGL +Y tangent space' if kind == 'normal' else ''}]",
        ))
    print(f"  {name:14s} {size}px  {time.time() - t0:5.1f}s")


