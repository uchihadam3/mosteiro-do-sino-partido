    col = lerp(metal_col, pcol, patina)
    col *= (1 - 0.2 * pores)[..., None]

    rough = lerp(0.36 + 0.08 * big + 0.14 * oxid + 0.08 * cavn - 0.06 * scratch, 0.84 + 0.04 * crust, patina)
    metal = np.clip(1 - patina * 1.05, 0, 1)
    ao = ao_from_height(h, k=8.0)
    return dict(albedo=col, height=h, rough=rough, ao=ao, metal=metal, strength=6.0)


