def tex_cloth_wool(n=512, seed=707):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    T = 64
    cell = n / T
    x = u * n + 0.9 * fbm(u, v, 8, 3, seed + 1)
    y = v * n + 0.9 * fbm(u, v, 8, 3, seed + 2)
    i = np.floor(x / cell).astype(np.int64) % T
    j = np.floor(y / cell).astype(np.int64) % T
    a = (x / cell) - np.floor(x / cell)
    b = (y / cell) - np.floor(y / cell)
    phase = (i + j) % 4
    warp_over = phase < 2
    tw = rng.uniform(0.85, 1.1, T).astype(F32)
    tf = rng.uniform(0.85, 1.1, T).astype(F32)
    cwp = rng.normal(0, 1, T).astype(F32)
    cwf = rng.normal(0, 1, T).astype(F32)

    def prof(t, width):
        return np.clip(1 - ((t - 0.5) / (0.5 * width)) ** 2, 0, 1) ** 0.6

    pw = prof(a, 0.98 * tw[i])
    pf = prof(b, 0.98 * tf[j])
    fpos_w = (phase + b) / 2.0
    fpos_f = (((i + j + 2) % 4) + a) / 2.0
    bul_w = 0.7 + 0.3 * np.sin(np.pi * np.clip(fpos_w, 0, 1))
    bul_f = 0.7 + 0.3 * np.sin(np.pi * np.clip(fpos_f, 0, 1))
    h = np.where(warp_over, pw * bul_w * tw[i], pf * bul_f * tf[j])
    fib_w = spectral(n, seed + 3, beta=0.4, ax=1, ay=6, fmax=300)
    fib_f = spectral(n, seed + 4, beta=0.4, ax=6, ay=1, fmax=300)
    fib = np.where(warp_over, fib_w, fib_f)
    fuzz = spectral(n, seed + 5, beta=0.6, fmin=40)
    slub = fbm(u, v, 4, 4, seed + 6)
    h = 0.35 + 0.5 * h + 0.06 * fib + 0.04 * fuzz
    h = gblur(h, 0.7).astype(F32)

    t = np.where(warp_over, 0.55 + 0.05 * cwp[i], 0.47 + 0.05 * cwf[j]) + 0.07 * fib + 0.15 * slub
    col = ramp(["#2e2924", "#463f37", "#5c544a", "#73695c"], t)
    shade = 0.75 + 0.25 * np.clip((h - 0.35) / 0.55, 0, 1)
    col *= shade[..., None]
    col = lerp(col, hexc("#7b7166"), smoothstep(1.4, 3.0, fuzz) * 0.35)
    rough = np.clip(0.9 + 0.03 * fuzz, 0, 1)
    ao = ao_from_height(h, k=4.0, radii=(1, 2.5, 6), weights=(1, 1, 0.5), floor=0.45)
    return dict(albedo=col, height=h, rough=rough, ao=ao, strength=4.0)


