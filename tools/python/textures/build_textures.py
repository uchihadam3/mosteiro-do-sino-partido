def tex_bronze_aged(n=512, seed=505):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    cast = fbm(u, v, 3, 6, seed + 1)
    pp = rng.random((900, 2))
    pd, pi = worley(u, v, pp, k=1)
    pores = np.clip(1 - pd / (rng.uniform(0.7, 2.4, len(pp))[pi] / n), 0, 1) * (rng.random(len(pp)) < 0.5)[pi]
    cw = WrapCanvas(n, ss=2)
