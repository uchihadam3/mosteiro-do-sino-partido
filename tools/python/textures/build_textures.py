def tex_wax(n=512, seed=909):
    rng = np.random.default_rng(seed)
    u, v = grid(n)
    x, y = u * n, v * n
    base = fbm(u, v, 2, 5, seed + 1)
    flow = spectral(n, seed + 2, beta=2.2, ax=1, ay=5)
    thick = np.zeros_like(x)
    for k in range(18):
        xc = rng.uniform(0, n)
        y0 = rng.uniform(0, n)
        L = rng.uniform(120, 400)
        w0 = rng.uniform(10, 26)
        wob_a = rng.uniform(1, 4)
        wob_f = rng.uniform(0.4, 1.4)
        sag_f = rng.uniform(9, 16)
        hk = rng.uniform(0.6, 1.0)
        dy = np.mod(y - y0, n)
        s = dy / L
        inside = (s <= 1.0).astype(F32)
        xw = xc + wob_a * np.sin(s * wob_f * np.pi * 2 + k)
        dx = np.abs(wrapd((x - xw) / n)) * n
        # wide at the top, narrowing neck, swollen rounded tip
        width = w0 * (1.15 - 0.6 * s) * (1 + 0.03 * np.sin(dy / (sag_f * 3) * 2 * np.pi))
        width = width * (1 + 0.45 * np.exp(-((s - 0.95) / 0.06) ** 2))
        prof = np.clip(1 - (dx / np.maximum(width, 1)) ** 2, 0, 1) ** 0.8
        cap = np.sqrt(np.clip(1 - ((s - 0.95) / 0.06).clip(0) ** 2, 0, 1))
        d = prof * inside * cap * hk * smoothstep(0.0, 0.25, s)
        thick = np.maximum(thick, d) + 0.18 * np.minimum(thick, d)
    thick = gblur(np.clip(thick, 0, 1.3), 2.2)
    h = 0.25 + 0.07 * base + 0.012 * flow + 0.26 * thick
    ripples = spectral(n, seed + 3, beta=1.6, fmin=20)
    h = (gblur(h, 0.8) + 0.003 * ripples).astype(F32)

    tn = np.clip(gblur(thick, 2.0) / 1.1, 0, 1)
    col = ramp(["#c2ae89", "#d3c3a1", "#e0d3b6", "#e9dfc8"], 0.45 + 0.3 * tn + 0.35 * base + 0.03 * flow)
    edge_glow = np.clip(tn * (1 - tn) * 4, 0, 1)
    col = lerp(col, hexc("#e4c890"), edge_glow * 0.18)
    sp = rng.random((70, 2))
    sd_, si = worley(u, v, sp, k=1)
    soot = np.clip(1 - sd_ / (rng.uniform(0.8, 2.0, len(sp))[si] / n), 0, 1) * (rng.random(len(sp)) < 0.5)[si]
    smudge = smoothstep(0.25, 0.45, fbm(u, v, 3, 4, seed + 4)) * (1 - tn)
    col = lerp(col, hexc("#4a4238"), np.clip(soot, 0, 1) * 0.7)
    col = lerp(col, hexc("#a89a80"), smudge * 0.3)
    rough = np.clip(0.4 - 0.12 * tn + 0.05 * base + 0.2 * smudge, 0, 1)
    ao = ao_from_height(h, k=5.0, floor=0.6)
    return dict(albedo=col, height=h, rough=rough, ao=ao, strength=8.0)


