def _lit(albedo, normal, rough, ao):
    L = np.array([-0.45, 0.55, 0.70], F32)
    L /= np.linalg.norm(L)
    H = L + np.array([0, 0, 1], F32)
    H /= np.linalg.norm(H)
    ndl = np.clip((normal * L).sum(-1), 0, 1)
    ndh = np.clip((normal * H).sum(-1), 0, 1)
    shin = 2.0 / np.clip(rough, 0.05, 1) ** 4
    spec = (1 - rough) ** 2 * ndh ** shin * 0.6
    lin = albedo ** 2.2
    c = lin * (0.18 * ao + 1.1 * ndl * ao ** 0.5)[..., None] * np.array([1.0, 0.86, 0.66]) + spec[..., None] * 0.5
    return np.clip(c ** (1 / 2.2), 0, 1)


def contact_sheet(path):
    from PIL import ImageFont

    sets = [p.name[: -len("_albedo.jpg")] for p in sorted(OUT.glob("*_albedo.jpg"))]
    cell = 256
    cols = 6
    W = cell * cols + 20
    Hh = (cell + 24) * len(sets) + 10
    sheet = Image.new("RGB", (W, Hh), (18, 17, 16))
    d = ImageDraw.Draw(sheet)
    for r, s in enumerate(sets):
        al = np.asarray(Image.open(OUT / f"{s}_albedo.jpg"), F32) / 255
        nm = np.asarray(Image.open(OUT / f"{s}_normal.jpg"), F32) / 255 * 2 - 1
        nm /= np.linalg.norm(nm, axis=-1, keepdims=True)
        ro = np.asarray(Image.open(OUT / f"{s}_rough.jpg"), F32) / 255
        ao = np.asarray(Image.open(OUT / f"{s}_ao.jpg"), F32) / 255
        lit = _lit(al, nm, ro, ao)
        tiles = [
            np.tile(al, (2, 2, 1)),
            (nm * 0.5 + 0.5),
            ro,
            ao,
            np.tile(lit, (2, 2, 1)),
            lit,
        ]
        y = 10 + r * (cell + 24)
        d.text((10, y), s, fill=(216, 199, 163))
        for c, t in enumerate(tiles):
            im = Image.fromarray(to8(t)).convert("RGB").resize((cell, cell), Image.LANCZOS)
            sheet.paste(im, (10 + c * cell, y + 14))
    sheet.save(path)
    print("contact sheet ->", path)


