    score = cloud + 0.05 * streaks
    patina = pct_step(score, 55, 90) ** 1.3
    crust_mid = spectral(n, seed + 4, beta=1.8, fmin=10)
    patina = np.clip(patina * (0.8 + 0.2 * np.tanh(crust_mid)) + 0.5 * gblur(cavn, 1.0) * pct_step(score, 30, 60), 0, 1)
    patina = gblur(patina, 1.2)
    crust = spectral(n, seed + 9, beta=1.0, fmin=40)
    h = (h + patina * (0.012 + 0.006 * crust)).astype(F32)

    oxid = pct_step(cloud, 25, 60)
    metal_col = ramp(["#33251a", "#4f3a24", "#6c5030", "#86673d", "#987548"], 0.55 + 0.7 * big + 0.25 * cast - 0.3 * cavn)
